import 'dart:io';
import 'package:flutter/services.dart';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:share_plus/share_plus.dart';

class ExportService {
  /// Convenience aliases for document export
  static Future<void> exportToPdf({
    required String title,
    required String content,
    String? documentType,
    String? standard,
  }) async {
    await printDocument(title, content);
  }

  static Future<void> exportToWord({
    required String title,
    required String content,
    String? documentType,
    String? standard,
  }) async {
    await shareWordDoc(title, content);
  }

  /// Generate a PDF document from title and markdown/plain text
  static Future<Uint8List> generatePdfBytes(String title, String content) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: (pw.Context context) {
          return pw.Container(
            alignment: pw.Alignment.centerRight,
            margin: const pw.EdgeInsets.only(bottom: 20),
            padding: const pw.EdgeInsets.only(bottom: 5),
            decoration: const pw.BoxDecoration(
              border: pw.Border(
                bottom: pw.BorderSide(color: PdfColors.indigo, width: 1.5),
              ),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  'GAHAR Accreditation Document',
                  style: const pw.TextStyle(
                    fontSize: 10,
                    color: PdfColors.grey700,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
                pw.Text(
                  title,
                  style: const pw.TextStyle(
                    fontSize: 10,
                    color: PdfColors.indigo900,
                  ),
                ),
              ],
            ),
          );
        },
        footer: (pw.Context context) {
          return pw.Container(
            alignment: pw.Alignment.centerRight,
            margin: const pw.EdgeInsets.only(top: 20),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  'Generated by GAHAR AI Accreditation Assistant',
                  style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
                ),
                pw.Text(
                  'Page ${context.pageNumber} of ${context.pagesCount}',
                  style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
                ),
              ],
            ),
          );
        },
        build: (pw.Context context) => [
          pw.Header(
            level: 0,
            child: pw.Text(
              title,
              style: const pw.TextStyle(
                fontSize: 22,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.indigo900,
              ),
            ),
          ),
          pw.SizedBox(height: 12),
          ...content.split('\n').map((line) {
            final trimmed = line.trim();
            if (trimmed.startsWith('# ')) {
              return pw.Padding(
                padding: const pw.EdgeInsets.only(top: 14, bottom: 6),
                child: pw.Text(
                  trimmed.substring(2),
                  style: const pw.TextStyle(
                    fontSize: 16,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColors.indigo800,
                  ),
                ),
              );
            } else if (trimmed.startsWith('## ') || trimmed.startsWith('### ')) {
              return pw.Padding(
                padding: const pw.EdgeInsets.only(top: 10, bottom: 4),
                child: pw.Text(
                  trimmed.replaceAll(RegExp(r'#+\s*'), ''),
                  style: const pw.TextStyle(
                    fontSize: 13,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColors.indigo700,
                  ),
                ),
              );
            } else if (trimmed.startsWith('- ') || trimmed.startsWith('* ')) {
              return pw.Padding(
                padding: const pw.EdgeInsets.only(left: 12, bottom: 3),
                child: pw.Row(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text('• ',
                        style: const pw.TextStyle(
                            fontWeight: pw.FontWeight.bold,
                            color: PdfColors.indigo)),
                    pw.Expanded(
                      child: pw.Text(
                        trimmed.substring(2),
                        style: const pw.TextStyle(fontSize: 10, lineSpacing: 2),
                      ),
                    ),
                  ],
                ),
              );
            } else if (trimmed.isEmpty) {
              return pw.SizedBox(height: 6);
            } else {
              return pw.Padding(
                padding: const pw.EdgeInsets.only(bottom: 4),
                child: pw.Text(
                  trimmed,
                  style: const pw.TextStyle(fontSize: 10, lineSpacing: 2),
                ),
              );
            }
          }),
        ],
      ),
    );

    return pdf.save();
  }

  /// Print document directly via printer / print dialog
  static Future<void> printDocument(String title, String content) async {
    final pdfBytes = await generatePdfBytes(title, content);
    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdfBytes,
      name: title,
    );
  }

  /// Share PDF document
  static Future<void> sharePdf(String title, String content) async {
    final pdfBytes = await generatePdfBytes(title, content);
    final outputDir = await getTemporaryDirectory();
    final sanitizedTitle =
        title.replaceAll(RegExp(r'[^\w\s\-]'), '_').replaceAll(' ', '_');
    final filePath = '${outputDir.path}/$sanitizedTitle.pdf';
    final file = File(filePath);
    await file.writeAsBytes(pdfBytes);

    await Share.shareXFiles(
      [XFile(filePath, mimeType: 'application/pdf')],
      subject: title,
      text: 'GAHAR Accreditation Document: $title',
    );
  }

  /// Export as text / Word compatible .doc format
  static Future<void> shareWordDoc(String title, String content) async {
    final outputDir = await getTemporaryDirectory();
    final sanitizedTitle =
        title.replaceAll(RegExp(r'[^\w\s\-]'), '_').replaceAll(' ', '_');
    final filePath = '${outputDir.path}/$sanitizedTitle.doc';

    final htmlContent = '''
<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<title>$title</title>
<style>
body { font-family: Arial, sans-serif; margin: 40px; color: #333; line-height: 1.6; }
h1 { color: #1a237e; border-bottom: 2px solid #1a237e; padding-bottom: 8px; }
h2, h3 { color: #283593; margin-top: 20px; }
ul { padding-left: 20px; }
li { margin-bottom: 6px; }
.footer { margin-top: 40px; font-size: 11px; color: #777; border-top: 1px solid #ddd; padding-top: 10px; }
</style>
</head>
<body>
<h1>$title</h1>
<div>
${content.replaceAll('\n', '<br>')}
</div>
<div class="footer">Generated by GAHAR AI Accreditation Assistant</div>
</body>
</html>
''';

    final file = File(filePath);
    await file.writeAsString(htmlContent);

    await Share.shareXFiles(
      [XFile(filePath, mimeType: 'application/msword')],
      subject: title,
      text: 'GAHAR Accreditation Document: $title (.doc)',
    );
  }
}
